-- 文章「主题声明的内容自定义字段」值（1.5.0 新增）。
--
-- 主题在 theme.json 的 contentFields 里声明一组内容字段（**文章与页面共用同一份**，
-- 例如 featuredImage、readingTime）。插件按声明白名单校验后，把**归一化后的键值对**
-- 序列化成 JSON 存进本列；读取时再解析回对象交给模板
-- （主题模板用 `{{ post.fields.featuredImage }}` 取值）。
--
-- 为什么不给每个字段各建一列：字段集合由主题动态声明，不同主题互不相同，
-- 逐字段建列需要随主题变更迁移表结构，且无法表达"未声明即不存在"的语义——
-- 用一列 JSON 承载，配合读写两侧按声明校验/过滤，才能做到换主题不炸。
--
-- 该列为新增可空列：历史文章保持 NULL（= 主题未声明或作者未填写），
-- 读取侧把 NULL 与解析失败一并降级为空对象，不改变既有文章的渲染行为。

ALTER TABLE rn_posts ADD COLUMN `fields` JSON NULL AFTER template;
